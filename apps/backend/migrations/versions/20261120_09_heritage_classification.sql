-- A reviewer withdrawing/changing an explicitly linked KG identity invalidates
-- its catalog evidence immediately. Existing RAG graph records are never edited.
CREATE FUNCTION refresh_catalog_linked_evidence() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE heritage_content SET input_revision=input_revision+1,classification_status='pending',updated_at=now()
    WHERE knowledge_entity_id=NEW.id;
    RETURN NEW;
END $$;
CREATE TRIGGER catalog_linked_evidence_trigger AFTER UPDATE OF name,type,summary,entry_status,
    source_document_id,source_passage_id ON entity FOR EACH ROW
    WHEN (OLD.* IS DISTINCT FROM NEW.*) EXECUTE FUNCTION refresh_catalog_linked_evidence();
