CREATE TABLE heritage_content (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_heritage_id BIGINT UNIQUE REFERENCES heritage(id) ON DELETE CASCADE,
    slug TEXT NOT NULL UNIQUE, title TEXT NOT NULL,
    tagline TEXT, headline TEXT, description TEXT, region TEXT,
    card_image_url TEXT, splash_image_url TEXT, publish_state VARCHAR(32) NOT NULL DEFAULT 'draft',
    entity_type_hint VARCHAR(16), entity_type VARCHAR(16), source_url TEXT,
    verified_metadata JSONB NOT NULL DEFAULT '{}'::jsonb CHECK(jsonb_typeof(verified_metadata)='object'),
    knowledge_entity_id UUID REFERENCES entity(id) ON DELETE SET NULL,
    source_document_id VARCHAR(36) REFERENCES knowledge_document(id) ON DELETE SET NULL,
    interactive_highlight_id BIGINT REFERENCES interactive_highlight(id) ON DELETE SET NULL,
    input_revision INTEGER NOT NULL DEFAULT 1 CHECK(input_revision>0),
    classified_revision INTEGER NOT NULL DEFAULT 0 CHECK(classified_revision>=0),
    classification_status VARCHAR(16) NOT NULL DEFAULT 'pending'
        CHECK(classification_status IN ('pending','applied','review','unclassified')),
    locked_by_admin BOOLEAN NOT NULL DEFAULT FALSE,
    is_featured BOOLEAN NOT NULL DEFAULT FALSE, featured_rank INTEGER NOT NULL DEFAULT 0 CHECK(featured_rank>=0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK(entity_type IS NULL OR entity_type IN ('place','artifact','collection','event','person','practice')),
    CHECK(entity_type_hint IS NULL OR entity_type_hint IN ('place','artifact','collection','event','person','practice'))
);
CREATE INDEX ix_heritage_content_public ON heritage_content(publish_state,classification_status,entity_type,id);
CREATE INDEX ix_heritage_content_title ON heritage_content(title,id);
CREATE INDEX ix_heritage_content_featured ON heritage_content(is_featured,featured_rank,id);
CREATE INDEX ix_heritage_content_kg_source ON heritage_content(knowledge_entity_id) WHERE knowledge_entity_id IS NOT NULL;

CREATE TABLE heritage_classifications (
    content_id BIGINT NOT NULL REFERENCES heritage_content(id) ON DELETE CASCADE,
    category_key VARCHAR(48) NOT NULL REFERENCES heritage_categories(key),
    is_primary BOOLEAN NOT NULL, confidence DOUBLE PRECISION NOT NULL CHECK(confidence BETWEEN 0 AND 1),
    classification_source VARCHAR(16) NOT NULL CHECK(classification_source IN ('rules','semantic','manual')),
    reasoning_summary TEXT NOT NULL, reviewed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY(content_id,category_key)
);
CREATE UNIQUE INDEX uq_heritage_classification_primary ON heritage_classifications(content_id) WHERE is_primary;
CREATE INDEX ix_heritage_classification_category ON heritage_classifications(category_key,content_id);

CREATE TABLE heritage_content_relations (
    subject_id BIGINT NOT NULL REFERENCES heritage_content(id) ON DELETE CASCADE,
    object_id BIGINT NOT NULL REFERENCES heritage_content(id) ON DELETE CASCADE,
    relation_type VARCHAR(32) NOT NULL CHECK(relation_type IN ('located_at','held_at','associated_with','member_of','depicts')),
    source_url TEXT NOT NULL, PRIMARY KEY(subject_id,object_id,relation_type), CHECK(subject_id<>object_id)
);
CREATE INDEX ix_content_relation_object ON heritage_content_relations(object_id);

CREATE TABLE heritage_classification_jobs (
    content_id BIGINT PRIMARY KEY REFERENCES heritage_content(id) ON DELETE CASCADE,
    generation INTEGER NOT NULL, status VARCHAR(16) NOT NULL DEFAULT 'PENDING'
        CHECK(status IN ('PENDING','RUNNING','RETRY','DONE','FAILED')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK(attempts>=0), available_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    leased_until TIMESTAMPTZ, lease_token UUID, last_error TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_classification_jobs_ready ON heritage_classification_jobs(status,available_at);
CREATE TABLE heritage_classification_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_id BIGINT NOT NULL REFERENCES heritage_content(id) ON DELETE CASCADE,
    run_id VARCHAR(36) NOT NULL, input_revision INTEGER NOT NULL, actor VARCHAR(100) NOT NULL,
    before JSONB NOT NULL, after JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_classification_audit_run ON heritage_classification_audit(run_id);
CREATE INDEX ix_classification_audit_content ON heritage_classification_audit(content_id);

-- Trigger work stays inside the source transaction; no HTTP/model calls occur.
CREATE FUNCTION heritage_content_revision() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='UPDATE' AND ROW(NEW.title,NEW.tagline,NEW.headline,NEW.description,NEW.region,
        NEW.card_image_url,NEW.splash_image_url,NEW.publish_state,NEW.entity_type_hint,
        NEW.source_url,NEW.verified_metadata,NEW.knowledge_entity_id,NEW.source_document_id,
        NEW.interactive_highlight_id,NEW.slug)
        IS DISTINCT FROM ROW(OLD.title,OLD.tagline,OLD.headline,OLD.description,OLD.region,
        OLD.card_image_url,OLD.splash_image_url,OLD.publish_state,OLD.entity_type_hint,
        OLD.source_url,OLD.verified_metadata,OLD.knowledge_entity_id,OLD.source_document_id,
        OLD.interactive_highlight_id,OLD.slug) THEN
        NEW.input_revision := OLD.input_revision+1;
        NEW.classification_status := 'pending';
        NEW.updated_at := now();
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER heritage_content_revision_trigger BEFORE UPDATE ON heritage_content
    FOR EACH ROW EXECUTE FUNCTION heritage_content_revision();

CREATE FUNCTION enqueue_heritage_classification() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='INSERT' OR NEW.input_revision IS DISTINCT FROM OLD.input_revision THEN
        INSERT INTO heritage_classification_jobs(content_id,generation)
        VALUES(NEW.id,NEW.input_revision)
        ON CONFLICT(content_id) DO UPDATE SET generation=EXCLUDED.generation,status='PENDING',
            attempts=0,available_at=now(),leased_until=NULL,lease_token=NULL,last_error=NULL,updated_at=now();
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER heritage_content_queue_trigger AFTER INSERT OR UPDATE ON heritage_content
    FOR EACH ROW EXECUTE FUNCTION enqueue_heritage_classification();

CREATE FUNCTION sync_heritage_catalog() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO heritage_content(source_heritage_id,slug,title,tagline,headline,description,region,
        card_image_url,splash_image_url,publish_state)
    VALUES(NEW.id,'heritage-'||NEW.slug,NEW.title,NEW.tagline,NEW.headline,NEW.description,NEW.region,
        NEW.card_image_url,NEW.splash_image_url,NEW.publish_state)
    ON CONFLICT(source_heritage_id) DO UPDATE SET slug=EXCLUDED.slug,title=EXCLUDED.title,
        tagline=EXCLUDED.tagline,headline=EXCLUDED.headline,description=EXCLUDED.description,
        region=EXCLUDED.region,card_image_url=EXCLUDED.card_image_url,
        splash_image_url=EXCLUDED.splash_image_url,publish_state=EXCLUDED.publish_state
    WHERE ROW(heritage_content.slug,heritage_content.title,heritage_content.tagline,heritage_content.headline,
        heritage_content.description,heritage_content.region,heritage_content.card_image_url,
        heritage_content.splash_image_url,heritage_content.publish_state)
        IS DISTINCT FROM ROW(EXCLUDED.slug,EXCLUDED.title,EXCLUDED.tagline,EXCLUDED.headline,
        EXCLUDED.description,EXCLUDED.region,EXCLUDED.card_image_url,EXCLUDED.splash_image_url,EXCLUDED.publish_state);
    RETURN NEW;
END $$;
CREATE TRIGGER heritage_catalog_source_trigger AFTER INSERT OR UPDATE OF slug,title,tagline,headline,
    description,region,card_image_url,splash_image_url,publish_state ON heritage
    FOR EACH ROW EXECUTE FUNCTION sync_heritage_catalog();

