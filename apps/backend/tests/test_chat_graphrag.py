"""Microsoft GraphRAG candidates must pass the same R2/BGE contract as hybrid."""
import os
import unittest
from types import SimpleNamespace
from unittest.mock import AsyncMock, patch

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession, create_async_engine

from apps.backend.api import chat as chat_api
from apps.backend.services.passages import PassageRepository
from apps.backend.tests.test_passages import MemoryStore, vectors
from apps.backend.db.import_passages import import_passages


@unittest.skipUnless(os.environ.get('PASSAGE_TEST_DATABASE_URL'), 'local PostgreSQL required')
class ChatGraphRagTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        self.engine = create_async_engine(os.environ['PASSAGE_TEST_DATABASE_URL'])
        self.session = AsyncSession(self.engine)
        self.addAsyncCleanup(self.engine.dispose)
        self.addAsyncCleanup(self.session.close)
        self.addAsyncCleanup(self.session.rollback)
        await self.session.begin()
        await self.session.execute(text('''
            CREATE TEMP TABLE passage (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                passage_index INT NOT NULL, location_note TEXT, embedding VECTOR(1024),
                object_key TEXT UNIQUE, content_hash TEXT, embedding_model TEXT
            ) ON COMMIT DROP
        '''))
        self.store = MemoryStore()
        self.store.bucket = 'knowledge'
        await import_passages(self.session, [
            {'text': 'Chùa Thiên Mụ được dựng năm 1601.', 'location_note': 'Chùa Thiên Mụ'},
            {'text': 'Chùa Thiên Mụ được trùng tu năm 1714.', 'location_note': 'Chùa Thiên Mụ'},
            {'text': 'Bún bò Huế có mắm ruốc.', 'location_note': 'Bún bò Huế'},
        ], store=self.store, embedder=vectors)
        self.rows = [dict(row) for row in (await self.session.execute(
            text('SELECT * FROM passage ORDER BY id')
        )).mappings()]
        self.repo = PassageRepository(
            self.session, store=self.store,
            # Vector finds only food; lexical/graph/subject omit the desired passage.
            embedder=lambda texts: [[1.0, 0.0] + [0.0] * 1022],
            reranker=lambda q, texts: [0.95 if '1601' in t else 0.6 for t in texts],
        )
        index = self.repo._index(self.rows)
        narrowed = SimpleNamespace(
            graph=index.graph, entity_ids={}, coverage=index.coverage,
            candidates=lambda q: {self.rows[1]['id']: {'bm25'}},
        )
        self.enterContext(patch.object(self.repo, '_index', return_value=narrowed))
        self.enterContext(patch.dict(os.environ, {'GRAPHRAG_ENABLED': 'true'}))
        self.global_query = self.enterContext(patch(
            'apps.backend.services.passages.run_global_query', new_callable=AsyncMock,
        ))
        self.graph_result = {
            'answer': 'UNTRUSTED GENERATED SUMMARY: built in 9999.',
            'snapshot_id': 'snapshot', 'context_reports': [{'report_id': '7'}],
            'sources': [{**{k: self.rows[0][k] for k in ('object_key', 'content_hash')},
                         'passage_id': self.rows[0]['id'], 'bucket': 'knowledge'}],
        }
        self.global_query.return_value = self.graph_result

    async def test_chat_reranks_graph_only_candidate_and_uses_original_r2_text(self):
        self.global_query.return_value = {
            **self.graph_result, 'sources': self.graph_result['sources'] * 2,
        }
        with (
            patch.object(chat_api, 'PassageRepository', return_value=self.repo),
            patch.object(chat_api, 'generate_response', return_value='Năm 1601.') as generate,
        ):
            response = await chat_api.chat(chat_api.ChatRequest(message='Chùa Thiên Mụ xây năm nào?'),
                                           db=self.session)
        self.assertEqual(response.sources[0]['passage_id'], self.rows[0]['id'])
        self.assertEqual(response.sources[0]['retrieval_methods'], ['microsoft_graphrag'])
        self.assertEqual(len(response.sources), len({s['passage_id'] for s in response.sources}))
        context = generate.call_args.kwargs['context']
        self.assertIn('1601', context)
        self.assertNotIn('9999', context)
        self.assertNotIn('UNTRUSTED', context)
        # GraphRAG is a candidate channel, not a relevance bypass.
        self.repo.reranker = lambda q, texts: [0.01 if '1601' in t else 0.9 for t in texts]
        result = await self.repo.search_evidence('Chùa Thiên Mụ xây năm nào?', limit=1)
        self.assertEqual([item.id for item in result.evidence], [self.rows[1]['id']])

    async def test_stale_unknown_or_wrong_bucket_graph_sources_cannot_enter_context(self):
        source = self.graph_result['sources'][0]
        for change in ({'content_hash': 'outdated'}, {'object_key': 'replaced'},
                       {'passage_id': 9999}, {'bucket': 'different-bucket'}):
            with self.subTest(change=change):
                self.global_query.return_value = {**self.graph_result, 'sources': [{**source, **change}]}
                result = await self.repo.search_evidence('Chùa Thiên Mụ xây năm nào?', limit=1)
                self.assertEqual([item.id for item in result.evidence], [self.rows[1]['id']])
                self.assertNotIn('microsoft_graphrag', result.evidence[0].retrieval_methods)

    async def test_graph_errors_timeout_and_disabled_mode_preserve_hybrid_answer(self):
        for error in (RuntimeError('token=private'), TimeoutError()):
            with self.subTest(error=type(error).__name__):
                self.global_query.side_effect = error
                result = await self.repo.search_evidence('Chùa Thiên Mụ xây năm nào?', limit=1)
                self.assertEqual([item.id for item in result.evidence], [self.rows[1]['id']])
        self.global_query.side_effect = AssertionError('disabled graph must not run')
        with patch.dict(os.environ, {'GRAPHRAG_ENABLED': 'false'}):
            result = await self.repo.search_evidence('Chùa Thiên Mụ xây năm nào?', limit=1)
        self.assertEqual([item.id for item in result.evidence], [self.rows[1]['id']])


if __name__ == '__main__':
    unittest.main()
