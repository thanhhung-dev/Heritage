"""Selection regressions with temporary pgvector data; no R2 writes or LLM calls."""
import os
import unittest
from unittest.mock import patch

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession, create_async_engine

from apps.backend.core.rag import evidence_context
from apps.backend.db.import_passages import import_passages
from apps.backend.services.passages import PassageRepository
from apps.backend.tests.test_passages import MemoryStore, vectors


@unittest.skipUnless(os.environ.get('PASSAGE_TEST_DATABASE_URL'), 'local PostgreSQL required')
class PassageSelectionTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        self.engine = create_async_engine(os.environ['PASSAGE_TEST_DATABASE_URL'])
        self.session = AsyncSession(self.engine)
        self.addAsyncCleanup(self.engine.dispose)
        self.addAsyncCleanup(self.session.close)
        self.addAsyncCleanup(self.session.rollback)
        await self.session.begin()
        await self.session.execute(text('''
            CREATE TEMP TABLE passage (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                passage_index INT NOT NULL, location_note TEXT, embedding VECTOR(1024),
                object_key TEXT UNIQUE, content_hash TEXT, embedding_model TEXT
            ) ON COMMIT DROP
        '''))
        self.store = MemoryStore()
        self.enterContext(patch.dict(os.environ, {'GRAPHRAG_ENABLED': 'false'}))

    async def search(self, rows, question, *, reranker=None, limit=2):
        await import_passages(self.session, rows, store=self.store, embedder=vectors)
        repo = PassageRepository(self.session, store=self.store, embedder=vectors,
                                 reranker=reranker or (lambda q, texts: [0.95] * len(texts)))
        return await repo.search_evidence(question, limit=limit)

    async def test_overview_label_is_not_the_subject_of_an_overview_question(self):
        source = 'Chùa Thiên Mụ tọa lạc tại Huế. Chùa được khởi lập năm 1601.'
        result = await self.search([{'text': source, 'location_note': 'tong quan'}],
                                  'Giới thiệu tổng quan chùa Thiên Mụ qua vị trí và lịch sử.')
        self.assertEqual([e.text for e in result.evidence], [source])
        self.assertIn('1601', evidence_context(result.evidence, result.query))

    async def test_spatial_reference_survives_without_repeating_the_full_subject(self):
        source = ('Chùa Thiên Mụ là ngôi cổ tự. '
                  'Qua cổng tam quan là sân rộng, hai bên có hai nhà Lôi Gia.')
        result = await self.search([{'text': source}],
                                  'Chùa Thiên Mụ có sân và hai nhà Lôi Gia ở vị trí nào?')
        self.assertEqual([e.text for e in result.evidence], [source])
        self.assertIn('hai bên có hai nhà Lôi Gia', evidence_context(result.evidence, result.query))

    async def test_reranker_receives_location_details_after_subject_introduction(self):
        source = ('Chùa Thiên Mụ tọa lạc tại Huế. '
                  'Hòn non bộ Linh Phong đặt trong vườn bên phải chánh điện.')
        result = await self.search([{'text': source}],
            'Trong chùa Thiên Mụ, hòn non bộ Linh Phong nằm ở đâu?',
            reranker=lambda q, texts: [0.95 if 'bên phải chánh điện' in t else 0.01 for t in texts])
        self.assertEqual([e.text for e in result.evidence], [source])
        self.assertIn('bên phải chánh điện', evidence_context(result.evidence, result.query))

    async def test_a_person_name_cannot_continue_across_a_heading_boundary(self):
        source = ('Chùa Thiên Mụ có tháp do vua Thiệu Trị\n'
                  'Tháp Phước Duyên đứng phía trước tam quan, nhìn ra sông Hương.')
        result = await self.search([{'text': source}],
                                  'Vì sao vị trí tháp Phước Duyên giúp nhận ra chùa Thiên Mụ?')
        self.assertEqual([e.text for e in result.evidence], [source])
        self.assertEqual(result.query.subject.lower(), 'tháp phước duyên')

    async def test_specific_question_keeps_bge_order_instead_of_promoting_a_definition(self):
        definition = 'Chùa Thiên Mụ là một ngôi chùa cổ tại Huế.'
        answer = 'Chùa Thiên Mụ có cổng tam quan làm cửa vào không gian thờ tự.'
        result = await self.search([{'text': definition}, {'text': answer}],
            'Chùa Thiên Mụ có cổng tam quan không?', limit=1,
            reranker=lambda q, texts: [0.99 if 'cửa vào' in t else 0.6 for t in texts])
        self.assertEqual([e.text for e in result.evidence], [answer])

    async def test_relationship_does_not_promote_biography_over_the_answer(self):
        biography = 'Chúa Nguyễn Phúc Chu lên ngôi năm 1691.'
        answer = 'Chúa Nguyễn Phúc Chu giao Tống Đức Đạt sửa chùa Thiên Mụ năm 1714.'
        result = await self.search([
            {'text': biography, 'location_note': 'nguyen phuc chu'},
            {'text': answer, 'location_note': 'S1'},
        ], 'Nguyễn Phúc Chu liên quan gì đến việc sửa chùa Thiên Mụ?', limit=1,
            reranker=lambda q, texts: [0.99 if 'Tống Đức Đạt' in t else 0.6 for t in texts])
        self.assertEqual([e.text for e in result.evidence], [answer])

    async def test_comparison_keeps_evidence_for_each_explicitly_named_subject(self):
        temple = 'Chùa Thiên Mụ là công trình thờ tự ở Huế.'
        bridge = 'Cầu Rồng là công trình giao thông ở Đà Nẵng.'
        result = await self.search([{'text': temple}, {'text': bridge}],
                                  'Chùa Thiên Mụ và Cầu Rồng khác nhau về chức năng gì?')
        self.assertEqual({e.text for e in result.evidence}, {temple, bridge})

    async def test_composite_title_does_not_require_contiguous_names_in_every_passage(self):
        intro = 'Cổng Tam Quan chùa Thiên Mụ là một công trình kiến trúc.'
        detail = 'Chùa Thiên Mụ có sân rộng sau cổng tam quan, hai bên là nhà Lôi Gia.'
        result = await self.search([{'text': intro}, {'text': detail}],
            'Cổng Tam Quan chùa Thiên Mụ liên hệ với hai nhà Lôi Gia như thế nào?',
            reranker=lambda q, texts: [0.99 if 'sân rộng' in t else 0.01 for t in texts])
        self.assertEqual([e.text for e in result.evidence], [detail])
