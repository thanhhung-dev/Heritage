CREATE FUNCTION validate_claim_value()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    expected_type TEXT;
    fallback_unit TEXT;
BEGIN
    SELECT value_type, default_unit
    INTO expected_type, fallback_unit
    FROM claim_field
    WHERE code = NEW.field_code;

    IF expected_type IS NULL THEN
        RETURN NEW;
    END IF;

    NEW.unit := COALESCE(NEW.unit, fallback_unit);

    IF expected_type = 'text'
       AND jsonb_typeof(NEW.value) <> 'string'
    THEN
        RAISE EXCEPTION
            'claim value for field % must be text',
            NEW.field_code
            USING ERRCODE = '23514';
    END IF;

    IF expected_type IN ('number', 'money')
       AND jsonb_typeof(NEW.value) <> 'number'
    THEN
        RAISE EXCEPTION
            'claim value for field % must be number',
            NEW.field_code
            USING ERRCODE = '23514';
    END IF;

    IF expected_type = 'boolean'
       AND jsonb_typeof(NEW.value) <> 'boolean'
    THEN
        RAISE EXCEPTION
            'claim value for field % must be boolean',
            NEW.field_code
            USING ERRCODE = '23514';
    END IF;

    IF expected_type = 'date'
       AND (
            jsonb_typeof(NEW.value) <> 'string'
            OR NEW.value #>> '{}' !~
               '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'
       )
    THEN
        RAISE EXCEPTION
            'claim value for field % must be YYYY-MM-DD',
            NEW.field_code
            USING ERRCODE = '23514';
    END IF;

    IF expected_type = 'year'
       AND (
            jsonb_typeof(NEW.value) <> 'number'
            OR NEW.value #>> '{}' !~
               '^-?[0-9]+$'
       )
    THEN
        RAISE EXCEPTION
            'claim value for field % must be integer year',
            NEW.field_code
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_claim_value
BEFORE INSERT OR UPDATE OF field_code, value, unit
ON claim
FOR EACH ROW
EXECUTE FUNCTION validate_claim_value();

