CREATE FUNCTION enforce_chat_answer_evidence() RETURNS TRIGGER LANGUAGE plpgsql AS $ $ DECLARE target_message_id BIGINT;

BEGIN IF TG_TABLE_NAME = 'chat_message_evidence' THEN IF TG_OP = 'DELETE' THEN target_message_id := OLD.message_id;

ELSE target_message_id := NEW.message_id;

END IF;

ELSE IF TG_OP = 'DELETE' THEN target_message_id := OLD.id;

ELSE target_message_id := NEW.id;

END IF;

END IF;

IF EXISTS (
    SELECT
        1
    FROM
        chat_message
    WHERE
        id = target_message_id
        AND role = 'assistant'
        AND response_status = 'answered'
)
AND NOT EXISTS (
    SELECT
        1
    FROM
        chat_message_evidence
    WHERE
        message_id = target_message_id
) THEN RAISE EXCEPTION 'answered chat message % requires at least one evidence passage',
target_message_id USING ERRCODE = '23514';

END IF;

IF TG_OP = 'DELETE' THEN RETURN OLD;

END IF;

RETURN NEW;

END;

$ $;

CREATE CONSTRAINT TRIGGER trg_chat_answer_requires_evidence
AFTER
INSERT
    OR
UPDATE
    ON chat_message DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION enforce_chat_answer_evidence();

CREATE CONSTRAINT TRIGGER trg_chat_evidence_cannot_orphan_answer
AFTER
    DELETE
    OR
UPDATE
    ON chat_message_evidence DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION enforce_chat_answer_evidence();

