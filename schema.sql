-- ADMIN / AUDIT
CREATE TABLE admin_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    session_token_hash TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id BIGINT NOT NULL REFERENCES admin_account(id),
    action TEXT NOT NULL,
    target_type TEXT NOT NULL,
    target_id BIGINT NOT NULL,
    detail JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_audit_log_admin_created ON audit_log (admin_id, created_at DESC);
CREATE INDEX idx_audit_log_target ON audit_log (target_type, target_id);

-- DOCUMENT / PASSAGE (RAG)
CREATE TABLE document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    source_url TEXT,
    source_type TEXT NOT NULL,
    content_hash TEXT NOT NULL,
    language_code TEXT,
    published_at DATE,
    accessed_at TIMESTAMPTZ,
    rights_note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_document_source_type CHECK (
        source_type IN (
            'official', 'academic', 'management', 'press',
            'encyclopedia', 'archive', 'book', 'other'
        )
    ),
    CONSTRAINT uq_document_source_version UNIQUE (source_url, content_hash)
);

CREATE TABLE passage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES document(id) ON DELETE CASCADE,
    passage_index INT NOT NULL,
    text TEXT NOT NULL,
    embedding VECTOR(1024),
    tsv TSVECTOR GENERATED ALWAYS AS (to_tsvector('simple', text)) STORED,
    page_number INT,
    location_note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_passage_index CHECK (passage_index >= 0),
    CONSTRAINT uq_passage_document_index UNIQUE (document_id, passage_index)
);

CREATE INDEX idx_passage_document ON passage (document_id);
CREATE INDEX idx_passage_tsv ON passage USING GIN (tsv);
CREATE INDEX idx_passage_text_trgm ON passage USING GIN (text gin_trgm_ops);
CREATE INDEX idx_passage_embedding
    ON passage USING HNSW (embedding vector_cosine_ops)
    WHERE embedding IS NOT NULL;

-- ENTITY
CREATE TABLE entity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type TEXT NOT NULL,
    canonical_name TEXT NOT NULL,
    normalized_name TEXT NOT NULL,
    subtype TEXT,
    in_scope BOOLEAN NOT NULL DEFAULT true,
    entry_status TEXT NOT NULL DEFAULT 'draft',
    depth_tier SMALLINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_entity_type CHECK (
        type IN ('person', 'place', 'event', 'artifact')
    ),
    CONSTRAINT chk_entity_entry_status CHECK (
        entry_status IN ('draft', 'reviewed', 'published', 'archived')
    ),
    CONSTRAINT chk_entity_depth_tier CHECK (
        depth_tier IS NULL OR depth_tier >= 0
    ),
    CONSTRAINT uq_entity_normalized_type UNIQUE (normalized_name, type)
);

CREATE INDEX idx_entity_name_trgm ON entity USING GIN (canonical_name gin_trgm_ops);
CREATE INDEX idx_entity_normalized_name ON entity (normalized_name);
CREATE INDEX idx_entity_scope_status_depth ON entity (in_scope, entry_status, depth_tier);
CREATE INDEX idx_entity_type ON entity (type);

CREATE TABLE entity_alias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id BIGINT NOT NULL REFERENCES entity(id) ON DELETE CASCADE,
    alias TEXT NOT NULL,
    normalized_alias TEXT NOT NULL,
    language_code TEXT,
    source_passage_id BIGINT REFERENCES passage(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_entity_alias_normalized UNIQUE (entity_id, normalized_alias)
);

CREATE INDEX idx_entity_alias_normalized ON entity_alias (normalized_alias);
CREATE INDEX idx_entity_alias_trgm ON entity_alias USING GIN (alias gin_trgm_ops);

CREATE TABLE entity_external_id (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id BIGINT NOT NULL REFERENCES entity(id) ON DELETE CASCADE,
    provider TEXT NOT NULL,
    external_id TEXT NOT NULL,
    url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_entity_external_provider_id UNIQUE (provider, external_id),
    CONSTRAINT uq_entity_provider UNIQUE (entity_id, provider)
