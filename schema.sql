-- CLAIM
CREATE TABLE claim_field (
    code TEXT PRIMARY KEY,
    label_vi TEXT NOT NULL,
    label_en TEXT,
    value_type TEXT NOT NULL DEFAULT 'text',
    default_unit TEXT,
    is_time_sensitive BOOLEAN NOT NULL DEFAULT false
);

CREATE TABLE claim (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id BIGINT NOT NULL REFERENCES entity(id) ON DELETE CASCADE,
    field_code TEXT NOT NULL REFERENCES claim_field(code),
    value JSONB NOT NULL,
    status TEXT NOT NULL DEFAULT 'proposed',
    confidence NUMERIC(4, 3),
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_claim_status CHECK (
        status IN ('proposed', 'accepted', 'disputed', 'rejected', 'superseded')
    ),
    CONSTRAINT chk_claim_confidence CHECK (
        confidence IS NULL OR confidence BETWEEN 0 AND 1
    )
);

CREATE INDEX idx_claim_entity_field ON claim (entity_id, field_code);
CREATE INDEX idx_claim_value_gin ON claim USING GIN (value);

-- RELATION
CREATE TABLE predicate (
    code TEXT PRIMARY KEY,
    label_vi TEXT NOT NULL,
    label_en TEXT,
    inverse_of TEXT REFERENCES predicate(code),
    is_symmetric BOOLEAN NOT NULL DEFAULT false
);

CREATE TABLE relation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id BIGINT NOT NULL REFERENCES entity(id) ON DELETE CASCADE,
    predicate TEXT NOT NULL REFERENCES predicate(code),
    object_id BIGINT NOT NULL REFERENCES entity(id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'proposed',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_relation_no_loop CHECK (subject_id <> object_id),
    CONSTRAINT chk_relation_status CHECK (
        status IN ('proposed', 'accepted', 'disputed', 'rejected', 'superseded')
    )
);

CREATE INDEX idx_relation_subject ON relation (subject_id, predicate);
CREATE INDEX idx_relation_object ON relation (object_id, predicate);

