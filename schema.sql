CREATE TABLE sky_preset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    turbidity DOUBLE PRECISION,
    rayleigh DOUBLE PRECISION,
    elevation DOUBLE PRECISION,
    azimuth DOUBLE PRECISION,
    exposure DOUBLE PRECISION,
    light_settings JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE scene (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    heritage_id BIGINT NOT NULL REFERENCES heritage(id) ON DELETE CASCADE,
    sequence INT NOT NULL,
    title TEXT NOT NULL,
    description TEXT,
    sky_preset_id BIGINT REFERENCES sky_preset(id) ON DELETE SET NULL,
    -- Camera nằm trong GLB (NULL = dùng camera mặc định của GLB)
    camera_node_name TEXT,
    -- Hoặc khai báo camera trực tiếp trong DB
    cam_start_pos JSONB,
    cam_start_target JSONB,
    cam_zoom_pos JSONB,
    cam_zoom_target JSONB,
    instant_move BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_scene_heritage_sequence UNIQUE (heritage_id, sequence),
    CONSTRAINT chk_scene_sequence CHECK (sequence >= 0)
);

CREATE INDEX idx_scene_heritage_sequence ON scene (heritage_id, sequence);

CREATE TABLE model_asset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scene_id BIGINT NOT NULL REFERENCES scene(id) ON DELETE CASCADE,
    file_url TEXT NOT NULL,
    format TEXT NOT NULL DEFAULT 'glb',
    lod_level INT NOT NULL DEFAULT 0,
    compression TEXT,
    file_size_bytes BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_model_asset_format CHECK (format IN ('glb', 'splat', 'sog')),
    CONSTRAINT chk_model_asset_lod CHECK (lod_level >= 0),
    CONSTRAINT chk_model_asset_compression CHECK (
        compression IS NULL
        OR compression IN ('draco', 'ktx2', 'meshopt', 'draco+ktx2', 'none')
    ),
    CONSTRAINT chk_model_asset_file_size CHECK (
        file_size_bytes IS NULL OR file_size_bytes >= 0
    ),
    CONSTRAINT uq_model_asset_scene_lod UNIQUE (scene_id, lod_level)
);

CREATE INDEX idx_model_asset_scene ON model_asset (scene_id);

