CREATE TABLE heritage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Basic information
    slug TEXT NOT NULL UNIQUE,
    title TEXT NOT NULL,
    tagline TEXT,
    headline TEXT,
    description TEXT,
    region TEXT,
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION,
    map_zoom DOUBLE PRECISION,
    display_map BOOLEAN NOT NULL DEFAULT TRUE,
    duration_seconds INT,
    launch_date DATE,
    publish_state TEXT NOT NULL DEFAULT 'draft',
    publish_date DATE,
    card_image_url TEXT,
    splash_image_url TEXT,
    hover_video_url TEXT,
    language1_id BIGINT REFERENCES language(id) ON DELETE SET NULL,
    language2_id BIGINT REFERENCES language(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
