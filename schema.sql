CREATE TABLE chat_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES chat_session(id) ON DELETE CASCADE,
    role TEXT NOT NULL,
    content TEXT NOT NULL,
    citations JSONB NOT NULL DEFAULT '[]' :: jsonb,
    response_status TEXT,
    abstained BOOLEAN NOT NULL DEFAULT false,
    retrieval_strategy TEXT,
    latency_ms INT,
    model TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_chat_message_role CHECK (
        role IN (
            'user',
            'assistant'
        )
    ),
    CONSTRAINT chk_chat_message_citations_array CHECK (
        jsonb_typeof(citations) = 'array'
    ),
    CONSTRAINT chk_chat_message_response CHECK (
        (
            role = 'user'
            AND response_status IS NULL
            AND abstained = false
        )
        OR (
            role = 'assistant'
            AND response_status IN (
                'answered',
                'clarify',
                'abstained'
            )
            AND abstained = (response_status = 'abstained')
        )
    ),
    CONSTRAINT chk_chat_message_latency CHECK (
        latency_ms IS NULL
        OR latency_ms >= 0
    )
);

CREATE INDEX idx_chat_message_session ON chat_message (session_id, created_at);

